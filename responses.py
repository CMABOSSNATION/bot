def detect_language(text):
    """Simple Luganda keyword detection"""
    luganda_words = [
        "muli", "osibye", "nze", "njagala", "webale", "kale",
        "nno", "era", "nga", "oba", "wano", "awo", "gyange",
        "laba", "tugende", "mutuuse", "enkya", "leero"
    ]
    text_lower = text.lower()
    for word in luganda_words:
        if word in text_lower:
            return "lg"
    return "en"
